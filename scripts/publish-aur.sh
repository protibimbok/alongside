#!/usr/bin/env bash
# Push concurtui-bin to the AUR after a GitHub release.
#
# Usage: publish-aur.sh <tag>
# Example: publish-aur.sh v0.1.0
#
# Requires: curl, git, ssh, sha256sum
# Environment: AUR_KEY (SSH private key) or SSH_AUTH_SOCK

set -euo pipefail

TAG="${1:?tag required (e.g. v0.1.0)}"
VERSION="${TAG#v}"
REPO="protibimbok/concurtui"
AUR_REPO="ssh://aur@aur.archlinux.org/concurtui-bin.git"
DESC="Run several commands in parallel and switch between their output in a TUI"

need() { command -v "$1" >/dev/null 2>&1 || { echo "required: $1" >&2; exit 1; }; }
need curl
need git
need sha256sum

sha256_of_url() {
  curl -fsSL "$1" | sha256sum | awk '{print $1}'
}

WORKDIR="$(mktemp -d)"
trap 'rm -rf "${WORKDIR}"' EXIT

if [ -n "${AUR_KEY:-}" ]; then
  KEY_FILE="${WORKDIR}/aur_key"
  printf '%s\n' "${AUR_KEY}" > "${KEY_FILE}"
  chmod 600 "${KEY_FILE}"
  export GIT_SSH_COMMAND="ssh -i ${KEY_FILE} -o StrictHostKeyChecking=accept-new"
fi

SHA_AMD64=$(sha256_of_url "https://github.com/${REPO}/releases/download/${TAG}/concurtui_linux_amd64.tar.gz")
SHA_ARM64=$(sha256_of_url "https://github.com/${REPO}/releases/download/${TAG}/concurtui_linux_arm64.tar.gz")

git clone "${AUR_REPO}" "${WORKDIR}/concurtui-bin"
cd "${WORKDIR}/concurtui-bin"

# Write PKGBUILD + .SRCINFO directly (ubuntu runners have no makepkg).
# The binaries are static musl builds, so there are no runtime depends.
cat > PKGBUILD <<EOF
# Generated by scripts/publish-aur.sh — do not edit by hand.
pkgname=concurtui-bin
pkgver=${VERSION}
pkgrel=1
pkgdesc="${DESC}"
arch=('x86_64' 'aarch64')
url="https://github.com/${REPO}"
license=('MIT')
provides=('concurtui')
conflicts=('concurtui')
# Versioned local filenames so makepkg/yay don't reuse a previous release's
# tarball from cache (the remote assets are unversioned).
source_x86_64=("concurtui_linux_amd64-\${pkgver}.tar.gz::https://github.com/${REPO}/releases/download/v\${pkgver}/concurtui_linux_amd64.tar.gz")
source_aarch64=("concurtui_linux_arm64-\${pkgver}.tar.gz::https://github.com/${REPO}/releases/download/v\${pkgver}/concurtui_linux_arm64.tar.gz")
sha256sums_x86_64=('${SHA_AMD64}')
sha256sums_aarch64=('${SHA_ARM64}')

package() {
  install -Dm755 "\${srcdir}/concurtui" "\${pkgdir}/usr/bin/concurtui"
  install -Dm644 "\${srcdir}/LICENSE" "\${pkgdir}/usr/share/licenses/\${pkgname}/LICENSE"
}
EOF

# pkgname must come after the pkgbase fields, or go-srcinfo rejects the file.
cat > .SRCINFO <<EOF
pkgbase = concurtui-bin
	pkgdesc = ${DESC}
	pkgver = ${VERSION}
	pkgrel = 1
	url = https://github.com/${REPO}
	arch = x86_64
	arch = aarch64
	license = MIT
	provides = concurtui
	conflicts = concurtui
	source_x86_64 = concurtui_linux_amd64-${VERSION}.tar.gz::https://github.com/${REPO}/releases/download/v${VERSION}/concurtui_linux_amd64.tar.gz
	sha256sums_x86_64 = ${SHA_AMD64}
	source_aarch64 = concurtui_linux_arm64-${VERSION}.tar.gz::https://github.com/${REPO}/releases/download/v${VERSION}/concurtui_linux_arm64.tar.gz
	sha256sums_aarch64 = ${SHA_ARM64}

pkgname = concurtui-bin
EOF

git add PKGBUILD .SRCINFO
if git diff --cached --quiet; then
  echo "AUR package already up to date for ${TAG}"
  exit 0
fi

git -c user.name="github-actions[bot]" \
    -c user.email="github-actions[bot]@users.noreply.github.com" \
    commit -m "Update to ${TAG}"
git push origin master

echo "Published concurtui-bin ${TAG} to AUR"
